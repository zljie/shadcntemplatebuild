import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';

const origin = process.env.COMPOSER_URL ?? 'http://127.0.0.1:3100';
const output = process.env.VERIFY_OUTPUT ?? 'test-results/projects';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(20000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const nav = () => page.locator('.catalog-topbar nav');
const projects = async () => {
  const response = await page.goto(`${origin}/projects`);
  assert.equal(response.status(), 200);
  await expect(page.getByRole('heading',{name:'我的项目',exact:true})).toBeVisible();
};
try {
  const response = await page.goto(`${origin}/resources`);
  assert.equal(response.status(), 200);
  await nav().getByRole('link',{name:'我的项目',exact:true}).click();
  await expect(page.getByRole('heading',{name:'我的项目',exact:true})).toBeVisible();
  await expect(page.locator('article.design-card').first()).toBeVisible();
  const search = page.getByRole('textbox',{name:'搜索页面',exact:true});
  await search.fill('no-project-matches-this-query');
  await expect(page.getByText('没有匹配的页面',{exact:true})).toBeVisible();
  await search.fill('');
  await page.getByRole('tab',{name:'应用框架',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Contextual Shell',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'布局',exact:true}).click();
  await expect(page.locator('.layout-grid article')).toHaveCount(3);
  await page.getByRole('tab',{name:'页面',exact:true}).click();
  await page.getByRole('radio',{name:/^数据库页面/}).click();
  await page.locator('article.design-card .design-thumb-link').first().click();
  await expect(page.getByRole('button',{name:'保存到页面',exact:true})).toBeVisible();
  await projects();
  await page.getByRole('radio',{name:/^模板/}).click();
  const template = page.locator('article.design-card').first();
  const name = await template.locator('h2').innerText();
  const href = await template.locator('.design-thumb-link').getAttribute('href');
  const templateId = new URL(href, origin).searchParams.get('template');
  const expectedTemplate = await (await page.request.get(`${origin}/api/templates/${templateId}`)).json();
  await expect(template.locator('.page-thumb-canvas')).toBeVisible();
  await template.locator('.design-thumb-link').click();
  await expect(page.getByRole('status').filter({hasText:`已打开模板「${name}」`})).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出 DSL',exact:true}).click();
  const document = JSON.parse(await readFile(await (await downloaded).path(),'utf8'));
  assert.deepEqual(document, expectedTemplate.template.document);
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await expect(page.getByText('已保存到本地',{exact:true})).toBeVisible();
  await projects();
  await page.getByRole('radio',{name:/^本地草稿/}).click();
  await expect(page.locator('article.design-card')).toHaveCount(1);
  await expect(page.locator('article.design-card h2')).toHaveText(document.name);
  await page.getByRole('link',{name:'继续编辑',exact:true}).click();
  await expect(page.getByText('草稿已恢复',{exact:true})).toBeVisible();
  await projects();
  await page.getByRole('link',{name:'新建页面',exact:true}).click();
  await expect(page.getByText('已创建空白页面',{exact:true})).toBeVisible();
  await projects();
  await page.screenshot({path:`${output}/desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:900});
  await expect(nav().getByRole('link',{name:'我的项目',exact:true})).toBeVisible();
  await page.screenshot({path:`${output}/mobile.png`,fullPage:true});
  assert.deepEqual(errors, []);
  console.log('PASS projects: resources navigation, list/search/source filters, Shell/layout tabs, database/template/draft editor entry, new page, mobile navigation, no runtime errors');
} finally {
  await browser.close();
}
